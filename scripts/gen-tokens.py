"""Generate apps/desktop/src/styles/tokens.css from design/tokens.json; --check fails if it is stale."""

import json
import pathlib
import re
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
SOURCE = ROOT / "design" / "tokens.json"
TARGET = ROOT / "apps" / "desktop" / "src" / "styles" / "tokens.css"
HEADER = "/* Generated by scripts/gen-tokens.py from design/tokens.json. Do not edit. */\n"


def css_value(value: str) -> str:
    alias = re.fullmatch(r"\{([A-Za-z0-9][A-Za-z0-9_.-]*)\}", value)
    return f"var(--{alias.group(1)})" if alias else value


def themed(tokens: list, theme: str, first: str) -> list[str]:
    lines = []
    for token in tokens:
        value = token["value"]
        if isinstance(value, dict):
            chosen = value.get(theme, value.get(first))
        elif theme == first:
            chosen = value
        else:
            continue
        if theme != first and isinstance(value, dict) and value.get(theme) is None:
            continue
        lines.append(f"  --{token['name']}: {css_value(chosen)};")
    return lines


def render(tokens: dict) -> str:
    themes = [t["id"] for t in tokens["color"]["themes"]]
    first, others = themes[0], themes[1:]
    colors = tokens["color"]["tokens"]
    shadows = tokens.get("shadow", {}).get("tokens", [])
    out = [HEADER]

    out.append(":root {")
    out += themed(colors + shadows, first, first)
    for family in ("spacing", "radius", "duration", "easing"):
        out += [f"  --{t['name']}: {t['value']};" for t in tokens.get(family, {}).get("tokens", [])]
    out += [f"  --family-{key}: {stack};" for key, stack in tokens["type"]["families"].items()]
    out.append("  color-scheme: light;")
    out.append("}\n")

    for theme in others:
        block = themed(colors + shadows, theme, first)
        out.append("@media (prefers-color-scheme: dark) {")
        out.append(f'  :root:not([data-theme="{first}"]) {{')
        out += ["  " + line for line in block]
        out.append(f"    color-scheme: {theme};")
        out.append("  }")
        out.append("}\n")
        out.append(f':root[data-theme="{theme}"] {{')
        out += block
        out.append(f"  color-scheme: {theme};")
        out.append("}\n")

    out.append("@theme inline {")
    out += [f"  --color-{t['name']}: var(--{t['name']});" for t in colors]
    out += [f"  --radius-{t['name'].removeprefix('radius-')}: var(--{t['name']});" for t in tokens["radius"]["tokens"]]
    out += [f"  --shadow-{t['name'].removeprefix('shadow-')}: var(--{t['name']});" for t in shadows]
    out += [f"  --font-{key}: var(--family-{key});" for key in tokens["type"]["families"]]
    out.append("}\n")

    for group in tokens["type"]["groups"]:
        for style in group["styles"]:
            family = style.get("family", group["family"])
            decl = [
                f"font-family: var(--family-{family})",
                f"font-size: {style['fontSize']}",
                f"line-height: {style['lineHeight']}",
                f"font-weight: {style['fontWeight']}",
            ]
            if "letterSpacing" in style:
                decl.append(f"letter-spacing: {style['letterSpacing']}")
            if family == "mono":
                decl.append("font-variant-numeric: tabular-nums")
            out.append(f".text-{style['name']} {{ {'; '.join(decl)}; }}")
    return "\n".join(out) + "\n"


def main() -> int:
    css = render(json.loads(SOURCE.read_text()))
    if "--check" in sys.argv[1:]:
        if not TARGET.exists() or TARGET.read_text() != css:
            print(f"gen-tokens: {TARGET.relative_to(ROOT)} is stale; run python3 scripts/gen-tokens.py", file=sys.stderr)
            return 1
        print("gen-tokens: ok")
        return 0
    TARGET.write_text(css)
    print(f"gen-tokens: wrote {TARGET.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
